import assert from 'node:assert/strict';
import { challengeDay, validateChallenge } from './challenge.mjs';
import { readFileSync } from 'node:fs';
const snapshot = JSON.parse(readFileSync(new URL('./snapshot.json', import.meta.url)));
assert.equal(challengeDay(new Date('2026-10-05T06:59:00Z')), 0);
assert.equal(challengeDay(new Date('2026-10-05T07:00:00Z')), 1);
assert.equal(challengeDay(new Date('2026-11-01T08:00:00Z')), 28);
assert.equal(validateChallenge(snapshot).entries.length, 15);
assert.throws(() => validateChallenge({ ...snapshot, entries: [{ ...snapshot.entries[0], url: 'javascript:alert(1)' }] }));
assert.throws(() => validateChallenge({ ...snapshot, entries: [snapshot.entries[0], snapshot.entries[0]] }));
console.log('Challenge boundary and data validation checks passed');
const { normalizePosts, validateUpdates } = await import('./sources.mjs');
const sample = { success: true, tweetId: '123', authorUsername: 'bcherny', text: 'A new Claude Code feature', createdAt: '2026-10-12T12:00:00Z' };
assert.equal(normalizePosts([sample, sample]).length, 1);
assert.equal(normalizePosts([{...sample,authorUsername:'someone_else'}]).length, 0);
assert.equal(normalizePosts([{...sample,isRetweet:true}]).length, 0);
assert.throws(()=>validateUpdates([{...normalizePosts([sample])[0],url:'https://evil.example/123'}]));
const { validateResets, resetDays } = await import('./challenge.mjs');
assert.equal(validateResets(snapshot.resets).length, 60);
assert.equal(resetDays(snapshot.resets).get('2026-10-11')[0].kind,'regular');
console.log('Source filtering, deduplication, reset history checks passed');
